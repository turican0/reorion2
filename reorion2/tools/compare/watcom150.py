"""Watcom register prototypes for the 1.31 game functions the 1.50 block calls.

The IDA 9.1 database of ORION150.EXE does not know that the game code (Watcom C) passes the first four
arguments in eax, edx, ebx, ecx. Hex-Rays then loses the register arguments and the results of those calls
in the block code (GCC, cdecl): calls padded with zeros by gen150.py, "variable is possibly undefined"
notes. This script writes an IDC that gives every called game function a __watcall type with the port's
argument count and return type (src/game/orion_common.h); run it on the database before the Hex-Rays step.

usage: python tools/compare/watcom150.py OUT.idc
"""
import glob, os, re, sys

DISS = 'C:/prenos/reorion2Data/diss150_ida91/'
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
GAME = os.path.join(ROOT, 'src', 'game')
BB = 0x1E0000
RANGES = [(0x1E0000, 0x203A2F), (0x21504F, 0x222A47), (0x22997F, 0x22A598)]


def split_args(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == ',' and depth == 0:
            out.append(cur)
            cur = ''
            continue
        depth += {'(': 1, ')': -1}.get(ch, 0)
        cur += ch
    if cur.strip():
        out.append(cur)
    return out


# port: address -> name (also the renamed ones), name -> (return type, [parameter types])
portname, defs = {}, {}
for p in glob.glob(os.path.join(GAME, 'orion_part_*.c')):
    lines = open(p, encoding='latin1').read().split('\n')
    for i, l in enumerate(lines):
        m = re.match(r'^//----- \(([0-9A-F]{8})\)', l)
        if m:
            a = int(m.group(1), 16)
            for k in range(i + 1, min(i + 40, len(lines))):
                d = re.match(r'^[A-Za-z_][\w \*]*?\b(\w+)\s*\(([^;]*)$', lines[k])
                if d and not lines[k].startswith(('//', '/*', '#', ' ', '\t', 'static')):
                    portname[a] = re.sub(r'_131$', '', d.group(1))
                    # the definition is the fallback prototype
                    hd = re.match(r'^([A-Za-z_][\w \*]*?)\b(\w+)\s*\((.*)\)\s*$', lines[k])
                    if hd and '...' not in hd.group(3):
                        defs[portname[a]] = (hd.group(1).strip(), [x.strip() for x in split_args(hd.group(3))
                                                                   if x.strip() and x.strip() != 'void'])
                    break
# link_stubs.c defines some game functions without a //----- marker
for m in re.finditer(r'(?m)^([A-Za-z_][\w \*]*?)\b(sub_([0-9A-F]{5,6}))\s*\(([^;{]*)\)\s*\{', open(os.path.join(GAME, 'link_stubs.c'), encoding='latin1').read()):
    a = int(m.group(3), 16)
    if a not in portname:
        portname[a] = m.group(2)
        defs[m.group(2)] = (m.group(1).strip(), [x.strip() for x in split_args(m.group(4)) if x.strip() and x.strip() != 'void'])
protos = {}
common = open(os.path.join(GAME, 'orion_common.h'), encoding='latin1').read()
for m in re.finditer(r'(?m)^(?!//)(?!extern\b)([A-Za-z_][\w \*]*?)\b(\w+)\s*\(([^;()]*(?:\([^()]*\)[^;()]*)*)\)\s*;', common):
    args = m.group(3).strip()
    if '...' in args:
        continue
    ps = [x.strip() for x in split_args(args) if x.strip() and x.strip() != 'void']
    protos[m.group(2)] = (m.group(1).strip(), ps)


def ida_type(t, ret=False):
    t = re.sub(r'\b(const|volatile|struct)\b', '', t).strip()
    if ret and t == 'void':
        return 'void'
    if '*' in t or '(' in t:
        return 'int'                     # pointers: 32-bit in the original
    t = re.sub(r'\s+\w+$', '', t) if ' ' in t and not t.startswith('unsigned') else t
    base = re.sub(r'\s+a\d+$', '', t)
    return {'char': 'char', 'int8_t': 'char', '_BYTE': 'unsigned __int8', 'uint8_t': 'unsigned __int8',
            'unsigned char': 'unsigned __int8', '_BOOL1': 'char', 'bool': 'char',
            'int16_t': '__int16', '_WORD': 'unsigned __int16', 'uint16_t': 'unsigned __int16',
            'unsigned __int16': 'unsigned __int16', '__int16': '__int16'}.get(base, 'int')


def param_type(p):
    m = re.match(r'^(.*?)(\b\w+)$', p)
    t = m.group(1) if m and m.group(1).strip() else p
    return ida_type(t.strip())


called = set()
rx = re.compile(r'^\w+:([0-9A-F]{6,8})\s+(call|jmp)\s+(?:near ptr\s+)?(sub_|loc_)([0-9A-F]{5,6})\b')
for l in open(DISS + 'ORION150.full.lst', encoding='latin1'):
    m = rx.match(l)
    if not m:
        continue
    a, t = int(m.group(1), 16), int(m.group(4), 16)
    if any(lo <= a < hi for lo, hi in RANGES) and t < BB and t in portname:
        called.add(t)

out = ['#include <idc.idc>',
       '/* generated by tools/compare/watcom150.py: Watcom register prototypes of the game functions the block calls */',
       'static main()', '{', '  auto n;', '  auto_wait();', '  n = 0;']
missing = []
for t in sorted(called):
    name = portname[t]
    pr = protos.get(name) or defs.get(name)
    if not pr:
        missing.append(name)
        continue
    ret, ps = pr
    regs = [('eax', 'ax', 'al'), ('edx', 'dx', 'dl'), ('ebx', 'bx', 'bl'), ('ecx', 'cx', 'cl')]

    def reg(k, t):
        return regs[k][2 if '__int8' in t or t == 'char' else 1 if '__int16' in t else 0]
    pl = []
    for k, p in enumerate(ps):
        pt = param_type(p)
        pl.append('%s a%d@<%s>' % (pt, k + 1, reg(k, pt)) if k < 4 else '%s a%d' % (pt, k + 1))
    rt = ida_type(ret, True)
    cc = '__userpurge' if len(ps) > 4 else '__usercall'   # Watcom: the callee pops the stack arguments
    decl = '%s %s f%s(%s)' % (rt, cc, '' if rt == 'void' else '@<%s>' % reg(0, rt), ', '.join(pl))
    out.append('  if (SetType(0x%X, "%s;")) n++; else msg("watcom150: SetType failed at 0x%X\\n");' % (t, decl, t))
# block functions IDA got wrong: 1E0023 is longjmp (setjmp = 1E0000), 1ECCDF the fatal error that ends in it;
# without noreturn IDA runs on into the next function and Hex-Rays gives their callers phantom parameters
BLOCK_TYPES = {
    0x1E0023: 'void __usercall f(int *a1@<eax>, int a2@<edx>)',
    0x1ECCDF: 'void __cdecl f(int a1, const char *a2, ...)',
}
for a, decl in sorted(BLOCK_TYPES.items()):
    out.append('  if (SetType(0x%X, "%s;")) n++; else msg("watcom150: SetType failed at 0x%X\\n");' % (a, decl, a))
    out.append('  set_func_flags(0x%X, get_func_flags(0x%X) | FUNC_NORET);' % (a, a))
out += ['  plan_and_wait(0x1E0000, 0x22A600);   /* the noreturn calls change the flow of their callers */',
        '  msg("watcom150: %d types set\\n", n);', '}']
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print('called game functions %d, typed %d, no port prototype %d' % (len(called), len(called) - len(missing), len(missing)))
if missing:
    print('  ' + ' '.join(sorted(missing)[:60]))
